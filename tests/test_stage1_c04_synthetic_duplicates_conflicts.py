def test_synthetic_event_id_determinism():
    """Verify generate_synthetic_event_id generates deterministic 32-char hex IDs."""
    id1 = generate_synthetic_event_id(
        seed=42,
        record_index=0,
        service="auth-service",
        endpoint="/api/v1/session",
        timestamp_str="2026-10-28T08:00:00+00:00",
    )
    id2 = generate_synthetic_event_id(
        seed=42,
        record_index=0,
        service="auth-service",
        endpoint="/api/v1/session",
        timestamp_str="2026-10-28T08:00:00+00:00",
    )
    # Distinct index must yield distinct ID
    id3 = generate_synthetic_event_id(
        seed=42,
        record_index=1,
        service="auth-service",
        endpoint="/api/v1/session",
        timestamp_str="2026-10-28T08:00:00+00:00",
    )

    assert len(id1) == 32
    assert id1 == id2
    assert id1 != id3


def test_generated_duplicate_records_retain_stable_event_ids(tmp_path):
    """Verify that synthetic log generation produces stable event IDs across repeated generation."""
    dir_run1 = tmp_path / "run1"
    dir_run2 = tmp_path / "run2"

    file1 = generate_logs(num_records=300, seed=42, output_dir=dir_run1)
    file2 = generate_logs(num_records=300, seed=42, output_dir=dir_run2)

    lines1 = file1.read_text(encoding="utf-8").splitlines()
    lines2 = file2.read_text(encoding="utf-8").splitlines()

    assert len(lines1) == len(lines2) == 300
    assert lines1 == lines2, "Repeated generation with the same seed must produce identical file content"

    # Inspect event IDs in the generated file
    seen_ids = set()
    duplicate_ids = set()

    for line in lines1:
        try:
            data = json.loads(line)
        except json.JSONDecodeError:
            continue
        if "event_id" in data:
            eid = data["event_id"]
            if eid in seen_ids:
                duplicate_ids.add(eid)
            seen_ids.add(eid)

    # 5% intentional duplicates in 300 records should produce multiple duplicates
    assert len(duplicate_ids) > 0, "Synthetic dataset must contain intentional duplicate event IDs"


def test_synthetic_identical_duplicates_classified_as_duplicates(tmp_path):
    """Verify identical duplicate records generated by the synthetic generator are classified as duplicates."""
    gen_dir = tmp_path / "logs"
    dataset_file = generate_logs(num_records=500, seed=42, output_dir=gen_dir, conflict_rate=0.0)

    db_path = tmp_path / "synth_dedup.db"
    cfg = PipelineConfig(
        database=DatabaseConfig(url=f"sqlite:///{db_path}"),
        reports_dir=tmp_path / "reports",
        quarantine_dir=tmp_path / "quarantine",
    )
    pipeline = LogAnalyticsPipeline(cfg)
    result = pipeline.run(files=[dataset_file])

    assert result["duplicate_count"] > 0, "Intentional duplicate records must be detected as duplicates"
    assert result["reconciliation"]["conflict_count"] == 0, "Identical duplicates must not be flagged as conflicts"
    assert result["reconciliation"]["is_balanced"] is True, "Reconciliation must balance"

    # Confirm accounting: input = valid + duplicate + conflict + rejected
    input_count = result["input_count"]
    reconciled_sum = (
        result["valid_count"]
        + result["duplicate_count"]
        + result["reconciliation"]["conflict_count"]
        + result["rejected_count"]
    )
    assert input_count == reconciled_sum

    # Idempotent re-run on the same DB: all valid events from run 1 must now be classified as duplicates
    pipeline_rerun = LogAnalyticsPipeline(cfg)
    result_rerun = pipeline_rerun.run(files=[dataset_file])

    assert result_rerun["valid_count"] == 0, "No new events should be inserted on identical re-run"
    assert result_rerun["duplicate_count"] == result["valid_count"] + result["duplicate_count"]
    assert result_rerun["reconciliation"]["conflict_count"] == 0
    assert result_rerun["reconciliation"]["is_balanced"] is True


def test_synthetic_conflicts_classified_as_conflicts_not_duplicates(tmp_path):
    """Verify records sharing an event ID but with different payloads are classified as conflicts."""
    gen_dir = tmp_path / "logs_conflict"
    # Generate dataset with 4% intentional conflicts
    dataset_file = generate_logs(num_records=500, seed=42, output_dir=gen_dir, conflict_rate=0.04)

    db_path = tmp_path / "synth_conflict.db"
    cfg = PipelineConfig(
        database=DatabaseConfig(url=f"sqlite:///{db_path}"),
        reports_dir=tmp_path / "reports",
        quarantine_dir=tmp_path / "quarantine",
    )
    pipeline = LogAnalyticsPipeline(cfg)
    result = pipeline.run(files=[dataset_file])

    assert result["reconciliation"]["conflict_count"] > 0, "Conflicting records must be classified as conflicts"
    assert result["duplicate_count"] > 0, "Identical duplicate records must still be detected as duplicates"
    assert result["valid_count"] > 0
    assert result["status"] == "PARTIAL_SUCCESS", "Run status must be PARTIAL_SUCCESS when conflicts exist"
    assert result["reconciliation"]["is_balanced"] is True, "Reconciliation accounting must balance with conflicts"


def test_in_batch_and_db_conflict_detection_with_synthetic_records(test_db_manager):
    """Verify deterministic in-batch and database-level conflict detection using create_conflicting_record."""
    writer = DatabaseWriter(test_db_manager, batch_size=100)

    run_id = "test-run-c04"
    writer.start_run(run_id, ["synthetic.jsonl"])

    base_time = datetime(2026, 10, 28, 12, 0, 0, tzinfo=timezone.utc)
    ev_orig = LogEventRecord(
        event_id="syn-c04-001",
        timestamp=base_time,
        severity=CanonicalSeverity.INFO,
        service="order-service",
        endpoint="/api/v1/orders",
        http_status=200,
        latency_ms=45.0,
        message="Order created successfully",
        source_file="synthetic.jsonl",
        source_line=1,
        run_id=run_id,
    )

    ev_dupe = LogEventRecord(
        event_id="syn-c04-001",
        timestamp=base_time,
        severity=CanonicalSeverity.INFO,
        service="order-service",
        endpoint="/api/v1/orders",
        http_status=200,
        latency_ms=45.0,
        message="Order created successfully",
        source_file="synthetic.jsonl",
        source_line=2,
        run_id=run_id,
    )

    ev_conflict_in_batch = LogEventRecord(
        event_id="syn-c04-001",
        timestamp=base_time,
        severity=CanonicalSeverity.INFO,
        service="order-service",
        endpoint="/api/v1/orders",
        http_status=500,  # conflicting status
        latency_ms=45.0,
        message="Order failed unexpectedly",  # conflicting message
        source_file="synthetic.jsonl",
        source_line=3,
        run_id=run_id,
    )

    # Batch 1: contains original, identical duplicate, and in-batch conflict
    res1 = writer.write_events_batch([ev_orig, ev_dupe, ev_conflict_in_batch])
    assert res1.inserted_count == 1
    assert res1.duplicate_count == 1
    assert res1.conflict_count == 1
    assert len(res1.conflicted_events) == 1
    assert res1.conflicted_events[0][0].event_id == "syn-c04-001"

    # Batch 2: subsequent batch with cross-batch conflict against stored DB record
    run_id_2 = "test-run-c04-batch2"
    writer.start_run(run_id_2, ["synthetic.jsonl"])

    ev_conflict_db = LogEventRecord(
        event_id="syn-c04-001",
        timestamp=base_time,
        severity=CanonicalSeverity.ERROR,  # conflicting severity
        service="order-service",
        endpoint="/api/v1/orders",
        http_status=200,
        latency_ms=999.0,  # conflicting latency
        message="Order created successfully",
        source_file="synthetic.jsonl",
        source_line=4,
        run_id=run_id_2,
    )
    res2 = writer.write_events_batch([ev_conflict_db])
    assert res2.inserted_count == 0
    assert res2.duplicate_count == 0
    assert res2.conflict_count == 1
    assert len(res2.conflicted_events) == 1
    assert res2.conflicted_events[0][0].event_id == "syn-c04-001"


def test_create_conflicting_record_helper():
    """Verify create_conflicting_record produces modified payloads while preserving event_id."""
    base = {
        "event_id": "test-eid-12345",
        "timestamp": "2026-10-28T12:00:00+00:00",
        "severity": "INFO",
        "service": "auth-service",
        "endpoint": "/api/v1/login",
        "http_status": 200,
        "latency_ms": 25.5,
        "message": "Login success",
    }

    # Default conflict modifies message and flips http_status
    c1 = create_conflicting_record(base)
    assert c1["event_id"] == base["event_id"]
    assert c1["message"] != base["message"]
    assert c1["http_status"] == 500

    # Explicit override of fields
    c2 = create_conflicting_record(
        base,
        message="Custom conflict message",
        http_status=401,
        severity="WARN",
        latency_ms=120.0,
    )
    assert c2["event_id"] == base["event_id"]
    assert c2["message"] == "Custom conflict message"
    assert c2["http_status"] == 401
    assert c2["severity"] == "WARN"
    assert c2["latency_ms"] == 120.0


def test_generator_cli_conflict_rate_validation():
    """Verify CLI argument validation for --conflict-rate."""
    # Negative conflict rate must fail
    res_neg = subprocess.run(
        [sys.executable, "scripts/generate_synthetic_logs.py", "--conflict-rate", "-0.1"],
        capture_output=True,
        text=True,
    )
    assert res_neg.returncode != 0
    assert "--conflict-rate must be between 0.0 and 1.0" in res_neg.stderr

    # Conflict rate >= 1.0 must fail
    res_high = subprocess.run(
        [sys.executable, "scripts/generate_synthetic_logs.py", "--conflict-rate", "1.5"],
        capture_output=True,
        text=True,
    )
    assert res_high.returncode != 0
    assert "--conflict-rate must be between 0.0 and 1.0" in res_high.stderr
